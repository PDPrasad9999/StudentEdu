import React, { useState } from 'react'
import {
  CalendarCheck,
  Plus,
  Filter,
  CheckCircle2,
  Circle,
  Clock,
  Sparkles,
  ChevronLeft,
  ChevronRight,
  BookOpen,
  Trash2,
  Edit2
} from 'lucide-react'
import { useApp } from '../context/AppContext'
import Card from '../components/common/Card'
import Button from '../components/common/Button'
import Badge from '../components/common/Badge'
import SessionModal from '../components/planner/SessionModal'
import { formatDate, formatTime } from '../utils/helpers'

export const StudyPlanner = () => {
  const {
    studySessions,
    subjects,
    toggleSessionComplete,
    deleteStudySession,
    addStudySession
  } = useApp()

  const [selectedSubjectFilter, setSelectedSubjectFilter] = useState('ALL')
  const [selectedStatusFilter, setSelectedStatusFilter] = useState('ALL')
  const [isModalOpen, setIsModalOpen] = useState(false)
  const [sessionToEdit, setSessionToEdit] = useState(null)
  const [selectedDate, setSelectedDate] = useState('2026-11-12')

  // Filtered sessions
  const filteredSessions = studySessions.filter((s) => {
    const matchesSubject =
      selectedSubjectFilter === 'ALL' || s.subjectId === selectedSubjectFilter
    const matchesStatus =
      selectedStatusFilter === 'ALL' ||
      (selectedStatusFilter === 'COMPLETED' && s.completed) ||
      (selectedStatusFilter === 'PLANNED' && !s.completed)
    const matchesDate = !selectedDate || s.date === selectedDate
    return matchesSubject && matchesStatus && matchesDate
  })

  // Calculate day stats
  const totalPlannedMinutes = filteredSessions.reduce(
    (acc, curr) => acc + (curr.durationMinutes || 0),
    0
  )
  const completedMinutes = filteredSessions
    .filter((s) => s.completed)
    .reduce((acc, curr) => acc + (curr.durationMinutes || 0), 0)

  // Smart Auto-Schedule Simulation
  const handleAutoSchedule = () => {
    const sampleBlock = {
      title: 'Automated Deep Focus: Tree Re-balancing & Problem Set',
      subjectId: 'sub_1',
      subjectCode: 'CS 301',
      date: selectedDate,
      startTime: '16:30',
      endTime: '17:45',
      durationMinutes: 75,
      notes: 'Generated by SmartEdu AI based on upcoming High-Priority deadline.',
      completed: false,
      status: 'Planned',
    }
    addStudySession(sampleBlock)
  }

  return (
    <div className="space-y-6">
      {/* Top Header Card */}
      <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-4 bg-white p-5 rounded-2xl border border-slate-200/80 shadow-xs">
        <div>
          <h2 className="text-xl font-bold text-slate-900">Weekly Study Planner</h2>
          <p className="text-xs text-slate-500 mt-1">
            Organize deep focus blocks, allocate time for assignments, and avoid last-minute cramming.
          </p>
        </div>

        <div className="flex items-center gap-2.5 flex-wrap">
          <Button
            variant="secondary"
            size="sm"
            icon={Sparkles}
            onClick={handleAutoSchedule}
            title="Auto-generate optimal study block based on deadline urgency"
          >
            Smart Suggest
          </Button>

          <Button
            variant="primary"
            size="sm"
            icon={Plus}
            onClick={() => {
              setSessionToEdit(null)
              setIsModalOpen(true)
            }}
          >
            Add Study Session
          </Button>
        </div>
      </div>

      {/* Date & Filter Controls */}
      <div className="bg-white p-4 rounded-2xl border border-slate-200/80 shadow-xs flex flex-wrap items-center justify-between gap-4">
        {/* Date Selector */}
        <div className="flex items-center gap-2">
          <span className="text-xs font-semibold text-slate-600">Select Date:</span>
          <input
            type="date"
            value={selectedDate}
            onChange={(e) => setSelectedDate(e.target.value)}
            className="px-3 py-1.5 text-xs bg-slate-50 border border-slate-200 rounded-xl focus:outline-none focus:ring-2 focus:ring-blue-500/20 font-medium text-slate-700"
          />
          <button
            onClick={() => setSelectedDate('2026-11-12')}
            className="text-xs font-semibold text-blue-600 hover:text-blue-800 ml-1"
          >
            Today
          </button>
        </div>

        {/* Filters */}
        <div className="flex items-center gap-3 flex-wrap">
          <div className="flex items-center gap-1.5">
            <Filter className="w-3.5 h-3.5 text-slate-400" />
            <span className="text-xs text-slate-500 font-medium">Subject:</span>
            <select
              value={selectedSubjectFilter}
              onChange={(e) => setSelectedSubjectFilter(e.target.value)}
              className="px-2.5 py-1.5 text-xs bg-slate-50 border border-slate-200 rounded-xl focus:outline-none text-slate-700"
            >
              <option value="ALL">All Subjects</option>
              {subjects.map((s) => (
                <option key={s.id} value={s.id}>
                  {s.code}
                </option>
              ))}
            </select>
          </div>

          <div className="flex items-center gap-1.5">
            <span className="text-xs text-slate-500 font-medium">Status:</span>
            <select
              value={selectedStatusFilter}
              onChange={(e) => setSelectedStatusFilter(e.target.value)}
              className="px-2.5 py-1.5 text-xs bg-slate-50 border border-slate-200 rounded-xl focus:outline-none text-slate-700"
            >
              <option value="ALL">All Status</option>
              <option value="PLANNED">Planned</option>
              <option value="COMPLETED">Completed</option>
            </select>
          </div>
        </div>
      </div>

      {/* Daily Progress Banner */}
      <div className="grid grid-cols-1 sm:grid-cols-3 gap-4">
        <div className="bg-blue-50 border border-blue-200 rounded-2xl p-4">
          <span className="text-xs font-semibold text-blue-700 uppercase">
            Total Planned
          </span>
          <div className="text-2xl font-bold text-blue-900 mt-1">
            {Math.floor(totalPlannedMinutes / 60)}h {totalPlannedMinutes % 60}m
          </div>
          <p className="text-xs text-blue-600 mt-0.5">
            {filteredSessions.length} sessions scheduled
          </p>
        </div>

        <div className="bg-emerald-50 border border-emerald-200 rounded-2xl p-4">
          <span className="text-xs font-semibold text-emerald-700 uppercase">
            Completed Focus
          </span>
          <div className="text-2xl font-bold text-emerald-900 mt-1">
            {Math.floor(completedMinutes / 60)}h {completedMinutes % 60}m
          </div>
          <p className="text-xs text-emerald-600 mt-0.5">
            {filteredSessions.filter((s) => s.completed).length} blocks completed
          </p>
        </div>

        <div className="bg-slate-50 border border-slate-200 rounded-2xl p-4">
          <span className="text-xs font-semibold text-slate-700 uppercase">
            Completion Rate
          </span>
          <div className="text-2xl font-bold text-slate-900 mt-1">
            {totalPlannedMinutes > 0
              ? Math.round((completedMinutes / totalPlannedMinutes) * 100)
              : 0}
            %
          </div>
          <div className="w-full bg-slate-200 rounded-full h-1.5 mt-2 overflow-hidden">
            <div
              className="bg-blue-600 h-full rounded-full transition-all duration-300"
              style={{
                width: `${
                  totalPlannedMinutes > 0
                    ? Math.round((completedMinutes / totalPlannedMinutes) * 100)
                    : 0
                }%`
              }}
            />
          </div>
        </div>
      </div>

      {/* Study Sessions Schedule List */}
      <Card>
        <div className="flex items-center justify-between mb-4">
          <div>
            <h3 className="font-bold text-slate-900 text-base">
              Scheduled Blocks for {formatDate(selectedDate)}
            </h3>
            <p className="text-xs text-slate-500">
              Check off sessions as you finish them to update your daily study metrics
            </p>
          </div>
        </div>

        {filteredSessions.length === 0 ? (
          <div className="py-12 text-center text-slate-400">
            <CalendarCheck className="w-12 h-12 mx-auto mb-3 text-slate-300" />
            <p className="text-base font-semibold text-slate-700">
              No sessions found for this day
            </p>
            <p className="text-xs text-slate-400 mt-1 max-w-sm mx-auto">
              Click "Add Study Session" to block out time for your courses or click "Smart Suggest".
            </p>
          </div>
        ) : (
          <div className="space-y-3">
            {filteredSessions.map((session) => (
              <div
                key={session.id}
                className={`p-4 rounded-2xl border transition-all duration-200 flex flex-col sm:flex-row sm:items-center justify-between gap-4 ${
                  session.completed
                    ? 'bg-slate-50/70 border-slate-200/70'
                    : 'bg-white border-slate-200 hover:border-blue-300 hover:shadow-xs'
                }`}
              >
                <div className="flex items-start sm:items-center gap-3.5">
                  <button
                    onClick={() => toggleSessionComplete(session.id)}
                    className="mt-0.5 sm:mt-0 p-1 rounded-full text-slate-400 hover:text-blue-600 transition-colors"
                    title={session.completed ? 'Mark planned' : 'Mark completed'}
                  >
                    {session.completed ? (
                      <CheckCircle2 className="w-6 h-6 text-emerald-500 fill-emerald-50" />
                    ) : (
                      <Circle className="w-6 h-6 text-slate-300 hover:text-blue-500" />
                    )}
                  </button>

                  <div>
                    <div className="flex items-center gap-2 mb-1 flex-wrap">
                      <Badge variant="primary" size="xs">
                        {session.subjectCode}
                      </Badge>
                      <span className="text-xs font-semibold text-slate-500 flex items-center gap-1">
                        <Clock className="w-3 h-3 text-slate-400" />
                        {formatTime(session.startTime)} - {formatTime(session.endTime)} ({session.durationMinutes}m)
                      </span>
                      {session.focusScore && (
                        <span className="text-[10px] font-bold px-1.5 py-0.5 rounded bg-amber-50 text-amber-700 border border-amber-200">
                          Focus Score: {session.focusScore}%
                        </span>
                      )}
                    </div>

                    <h4
                      className={`text-sm font-semibold ${
                        session.completed
                          ? 'line-through text-slate-500'
                          : 'text-slate-900'
                      }`}
                    >
                      {session.title}
                    </h4>

                    {session.notes && (
                      <p className="text-xs text-slate-500 mt-1 italic">
                        "{session.notes}"
                      </p>
                    )}
                  </div>
                </div>

                {/* Actions */}
                <div className="flex items-center gap-2 self-end sm:self-center">
                  <button
                    onClick={() => {
                      setSessionToEdit(session)
                      setIsModalOpen(true)
                    }}
                    className="p-2 rounded-xl text-slate-400 hover:text-slate-700 hover:bg-slate-100 transition-colors"
                    title="Edit session"
                  >
                    <Edit2 className="w-4 h-4" />
                  </button>
                  <button
                    onClick={() => deleteStudySession(session.id)}
                    className="p-2 rounded-xl text-slate-400 hover:text-rose-600 hover:bg-rose-50 transition-colors"
                    title="Delete session"
                  >
                    <Trash2 className="w-4 h-4" />
                  </button>
                </div>
              </div>
            ))}
          </div>
        )}
      </Card>

      {/* Session Modal */}
      <SessionModal
        isOpen={isModalOpen}
        onClose={() => {
          setIsModalOpen(false)
          setSessionToEdit(null)
        }}
        sessionToEdit={sessionToEdit}
      />
    </div>
  )
}

export default StudyPlanner
